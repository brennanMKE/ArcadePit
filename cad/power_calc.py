"""5 V power plan for the pit benches.

Reads the layout from out/pit_meshes.json (written by cad/arcade_pit.py) and sizes the
power system: one 5 V supply per half of the ring (the two walk-in gaps split the ring
into a west and an east half of 5 benches), a feeder from each supply into the power base
under the middle end bench, a fused distribution block there, and a separate home run
through the bases to each bench's blind-mate connector.

Outputs (out/power/):
  * printed summary
  * power_sheet.md: wire gauges, fuses, supply, voltage at each bench, parts list
  * wiring_plan.svg: plan view of the ring with every run

Run:  python3 cad/power_calc.py [--strip-w-per-m 18] [--feeder-m 2.0] [--slack-m 0.6]
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "out" / "power"

# copper, ohms per metre (one conductor)
AWG = {18: 0.02095, 16: 0.01317, 14: 0.008286, 12: 0.005211, 10: 0.003277}
# Mean Well LRS-series 5 V supplies (check the current datasheet before buying)
PSUS = [("Mean Well LRS-100-5", 18.0), ("Mean Well LRS-150F-5", 22.0), ("Mean Well LRS-200-5", 40.0)]
FUSES = [3, 5, 7.5, 10, 15, 20, 25, 30]   # ATO/ATC blade ratings, A
V_NOM, V_MAX_LED = 5.0, 5.3                # WS2812-class strips: 3.5-5.3 V supply range


def local_to_pit(pl, lx, ly):
    r = math.radians(pl["rot"])
    x, y = pl["pos"]
    return x + lx * math.cos(r) - ly * math.sin(r), y + lx * math.sin(r) + ly * math.cos(r)


def ring_path(P, start, end, half_sign, c_y, is_end):
    """Route along the conduit in the shared base: down the end run, round the corner pull box,
    along the side run; never across the open pit floor."""
    xe = half_sign * (P["OUTER_L"] / 2 - c_y)
    ys = P["OUTER_W"] / 2 - c_y
    (fx, fy), (cx, cy) = start, end
    if is_end:                                           # end bench: stay in the end run
        return [(fx, fy), (xe, fy), (xe, cy), (cx, cy)]
    yr = math.copysign(ys, cy)                           # side bench: up the end, along the side
    return [(fx, fy), (xe, fy), (xe, yr), (cx, yr), (cx, cy)]


def path_len(pts):
    return sum(math.dist(a, b) for a, b in zip(pts, pts[1:])) / 1000


def drop(length_m, amps, ohm_per_m):
    return 2 * length_m * ohm_per_m * amps          # out and back


def pick_gauge(length_m, amps, budget_v):
    for g in sorted(AWG, reverse=True):              # thinnest first
        if drop(length_m, amps, AWG[g]) <= budget_v:
            return g
    return min(AWG)


def compute(data, a):
    pw, places = data["power"], data["placements"]
    amps = pw["strip_len"] / 1000 * a.strip_w_per_m / V_NOM
    fuse = next(f for f in FUSES if f >= amps * 1.25)
    halves = {}
    for i, pl in enumerate(places):
        halves.setdefault(pl["half"], []).append(i)
    plan = {}
    for half, idx in halves.items():
        src = next(i for i in idx if places[i]["base"] == "base_power")
        fx, fy = local_to_pit(places[src], *pw["fuse"])
        inlet = local_to_pit(places[src], *pw["feeder"])
        runs = []
        for i in idx:
            cx, cy = local_to_pit(places[i], *pw["conn"])
            path = ring_path(data["params"], (fx, fy), (cx, cy), -1 if half == "west" else 1, pw["c_y"],
                             places[i]["side"] in ("west", "east"))
            length = path_len(path) + a.slack_m
            g = pick_gauge(length, amps, a.run_budget_v)
            runs.append({"bench": i, "side": places[i]["side"], "conn": (cx, cy), "path": path, "len_m": length, "awg": g,
                         "drop": drop(length, amps, AWG[g])})
        i_half = amps * len(idx)
        psu = next((p for p in PSUS if p[1] * 0.8 >= i_half), PSUS[-1])
        fg = pick_gauge(a.feeder_m, i_half, a.feeder_budget_v)
        f_drop = drop(a.feeder_m, i_half, AWG[fg])
        worst = max(r["drop"] for r in runs)
        v_set = min(V_MAX_LED, round((V_NOM + f_drop + worst / 2) * 20) / 20)
        for r in runs:
            r["v_full"] = v_set - f_drop - r["drop"]
        plan[half] = {"src": src, "fuse_at": (fx, fy), "inlet": inlet, "runs": runs, "amps": i_half,
                      "psu": psu, "feeder_awg": fg, "feeder_drop": f_drop, "v_set": v_set,
                      "main_fuse": next(f for f in FUSES if f >= i_half * 1.25)}
    return amps, fuse, plan


