def plan_svg(data, plan):
    P, places = data["params"], data["placements"]
    D, Lb = P["D"], P["L"]
    xo, yo = P["OUTER_L"] / 2, P["OUTER_W"] / 2
    s, pad = 0.2, 70
    W, H = 2 * (xo + 600) * s + 2 * pad, 2 * yo * s + 2 * pad + 60
    X = lambda x: pad + (x + xo + 600) * s
    Y = lambda y: pad + 40 + (yo - y) * s
    cols = {"west": "#d1495b", "east": "#2e86ab"}
    o = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W:.0f} {H:.0f}" width="{W:.0f}" height="{H:.0f}" '
         'font-family="Helvetica, Arial, sans-serif" font-size="11">',
         f'<rect width="{W:.0f}" height="{H:.0f}" fill="#fbfaf7"/>',
         f'<text x="{pad}" y="34" font-size="16" font-weight="bold" fill="#1d1b18">5 V WIRING PLAN</text>',
         f'<text x="{pad + 170}" y="34" fill="#7b7468">one home run per bench from the fuse block in each power base</text>']
    tl, tw = P["table"][0], P["table"][1]
    o.append(f'<rect x="{X(-tl / 2):.1f}" y="{Y(tw / 2):.1f}" width="{tl * s:.1f}" height="{tw * s:.1f}" '
             'fill="#e6e1d8" stroke="#7b7468"/>')
    o.append(f'<text x="{X(0):.1f}" y="{Y(0) + 4:.1f}" text-anchor="middle" fill="#7b7468">arcade table</text>')
    for i, pl in enumerate(places):
        corners = [local_to_pit(pl, lx, ly) for lx, ly in ((0, 0), (Lb, 0), (Lb, D), (0, D))]
        pts = " ".join(f"{X(x):.1f},{Y(y):.1f}" for x, y in corners)
        pwr = pl["base"] == "base_power"
        o.append(f'<polygon points="{pts}" fill="{"#fff4d6" if pwr else "#ffffff"}" stroke="#1d1b18" stroke-width="1.2"/>')
        cx = sum(c[0] for c in corners) / 4
        cy = sum(c[1] for c in corners) / 4
        nx, ny = local_to_pit(pl, Lb / 2, D / 2)
        o.append(f'<text x="{X(nx):.1f}" y="{Y(ny) - 4:.1f}" text-anchor="middle" fill="#7b7468">bench {i}</text>')
    for half, h in plan.items():
        c = cols.get(half, "#444")
        fx, fy = h["fuse_at"]
        for r in h["runs"]:
            cx, cy = r["conn"]
            pts = " ".join(f"{X(x):.1f},{Y(y):.1f}" for x, y in r["path"])
            o.append(f'<polyline points="{pts}" fill="none" stroke="{c}" stroke-width="1.6" opacity="0.85"/>')
            o.append(f'<circle cx="{X(cx):.1f}" cy="{Y(cy):.1f}" r="3.5" fill="{c}"/>')
            # label inside the bench, toward the pit centre
            pl = places[r["bench"]]
            mx, my = local_to_pit(pl, Lb / 2, D / 2)
            o.append(f'<text x="{X(mx):.1f}" y="{Y(my) + 12:.1f}" font-size="10" text-anchor="middle" fill="{c}">'
                     f'{r["len_m"]:.1f} m · {r["awg"]} AWG</text>')
        o.append(f'<rect x="{X(fx) - 7:.1f}" y="{Y(fy) - 7:.1f}" width="14" height="14" fill="{c}"/>')
        ix, iy = h["inlet"]
        side = -1 if half == "west" else 1
        px = ix + side * 420
        o.append(f'<line x1="{X(ix):.1f}" y1="{Y(iy):.1f}" x2="{X(px):.1f}" y2="{Y(iy):.1f}" stroke="{c}" stroke-width="3"/>')
        o.append(f'<line x1="{X(ix):.1f}" y1="{Y(iy):.1f}" x2="{X(fx):.1f}" y2="{Y(fy):.1f}" stroke="{c}" stroke-width="3"/>')
        bx = X(px) - (90 if side < 0 else 0)
        o.append(f'<rect x="{bx:.1f}" y="{Y(iy) - 22:.1f}" width="90" height="44" rx="4" fill="#1d1b18"/>')
        o.append(f'<text x="{bx + 45:.1f}" y="{Y(iy) - 4:.1f}" text-anchor="middle" fill="#fff">5 V supply</text>')
        o.append(f'<text x="{bx + 45:.1f}" y="{Y(iy) + 11:.1f}" text-anchor="middle" fill="#ffd27a">{h["v_set"]:.2f} V</text>')
    o.append(f'<rect x="{pad}" y="{H - 30:.0f}" width="12" height="12" fill="#fff4d6" stroke="#1d1b18"/>'
             f'<text x="{pad + 18}" y="{H - 20:.0f}" fill="#1d1b18">power base (fuse block)</text>'
             f'<circle cx="{pad + 190}" cy="{H - 24:.0f}" r="3.5" fill="#1d1b18"/>'
             f'<text x="{pad + 198}" y="{H - 20:.0f}" fill="#1d1b18">bench connector</text>')
    o.append("</svg>")
    return "\n".join(o)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--strip-w-per-m", type=float, default=18.0,
                    help="strip power at full white, W/m (5 V WS2812B 60/m is about 18)")
    ap.add_argument("--feeder-m", type=float, default=2.0, help="supply to power-base inlet, one way, m")
    ap.add_argument("--slack-m", type=float, default=0.6, help="added to each run for rises and service loops, m")
    ap.add_argument("--run-budget-v", type=float, default=0.20, help="max drop per run at full white, V")
    ap.add_argument("--feeder-budget-v", type=float, default=0.15, help="max feeder drop at full load, V")
    a = ap.parse_args(argv)
    data = json.loads((ROOT / "out" / "pit_meshes.json").read_text())
    amps, fuse, plan = compute(data, a)
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "power_sheet.md").write_text(sheet(data, a, amps, fuse, plan))
    (OUT / "wiring_plan.svg").write_text(plan_svg(data, plan))
    print(f"per bench {amps:.2f} A, {fuse:g} A fuse per run")
    for half, h in plan.items():
        runs = ", ".join(f"#{r['bench']} {r['len_m']:.1f}m/{r['awg']}AWG {r['v_full']:.2f}V" for r in h["runs"])
        print(f"{half}: {h['amps']:.1f} A, {h['psu'][0]}, set {h['v_set']:.2f} V, feeder {h['feeder_awg']} AWG; {runs}")
    print("wrote", OUT / "power_sheet.md", OUT / "wiring_plan.svg")


if __name__ == "__main__":
    main()
